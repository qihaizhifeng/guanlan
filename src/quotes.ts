export function getQuoteByDate(month: number, day: number): DailyQuote | null {
  const key = `${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`
  return quotesMap[key] ?? null
}

export function getTodayQuote(): DailyQuote | null {
  const now = new Date()
  return getQuoteByDate(now.getMonth() + 1, now.getDate())
}
